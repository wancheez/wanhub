"""Явная команда правки картинки или нет — решает маршрут фото в чате.

Фото с подписью (и текстовый реплай на фото) идут двумя путями:
  • подпись похожа на команду правки («сделай фон синим», «Чат, убери людей»)
    → сразу Gemini, без Claude: бесплатно и быстро;
  • всё остальное («что это?», «переведи текст», «можешь сделать его рыжим?»)
    → Claude вместе с картинкой; у него есть тул edit_image, и если он решит,
    что просят правку, правка выполнится всё равно.

Поэтому регэксп намеренно консервативный: ловим только императивы в начале
фразы. Инфинитивы («сделать») и вопросы (всё с «?» в конце) не ловим — их
разберёт Claude, который видит картинку и контекст.
"""

import re

# Вежливые/вводные слова перед глаголом. «можешь / можно» сюда намеренно
# НЕ входят: это вопрос («можешь сделать…?»), его отдаём Claude.
_LEAD = r"(?:(?:чат|пожалуйста|плиз|пж|а|давай|ну|теперь|ещё|еще|и|попробуй|просто)[\s,]+)*"

# Только повелительное наклонение (2-е лицо; «-те» добавляется ниже).
_VERBS = (
    r"сделай|убери|удали|добавь|замени|отредактируй|измени|поменяй|перекрась|"
    r"дорисуй|пририсуй|подрисуй|нарисуй|сотри|вставь|обрежь|поверни|разверни|"
    r"преврати|стилизуй|перерисуй|раскрась|отрази|размой|затемни|осветли|"
    r"увеличь|уменьши|улучши|исправь|поправь|подправь|почисти|очисти|состарь|"
    r"омолоди|переделай|обработай|отретушируй|отзеркаль"
)
EDIT_RE = re.compile(rf"^\s*{_LEAD}(?:{_VERBS})(?:те)?\b", re.IGNORECASE)


def looks_like_edit(text: str) -> bool:
    """True для явной команды правки картинки («сделай фон синим», «Чат, убери людей»).

    Вопросы («что это?», «можешь сделать его рыжим?») и вообще всё, что
    заканчивается на «?», → False: такие сообщения уходят Claude, который сам
    решает, звать ли edit_image.
    """
    t = text.strip()
    if not t or t.endswith("?"):
        return False
    return EDIT_RE.match(t) is not None
