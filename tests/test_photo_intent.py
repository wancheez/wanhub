"""Регэксп явной команды правки картинки (app.bot.photo_intent)."""

import pytest

from app.bot.photo_intent import looks_like_edit


@pytest.mark.parametrize(
    "text",
    [
        "сделай фон синим",
        "Сделай фон синим!",
        "Чат, убери людей",
        "пожалуйста, добавь шляпу",
        "а давай замени небо",
        "сделайте его рыжим",
        "сделай так, чтобы было ночью",
        "перерисуй в стиле аниме",
        "  Отредактируй: сделай ярче ",
        "плиз, отзеркаль",
    ],
)
def test_edit_commands(text: str) -> None:
    assert looks_like_edit(text) is True


@pytest.mark.parametrize(
    "text",
    [
        "что это?",
        "чей это герб?",
        "переведи текст на фото",
        "можешь сделать его рыжим?",
        "можно его рыжим",
        "сделай фон синим?",  # вопрос — пусть решает Claude
        "кто на фото",
        "красиво",
        "",
        "   ",
        "сделать фон синим",  # инфинитив
        "я сделал фон синим, как?",
        "убери, пожалуйста?",
        "ну попробуй убрать фон",  # инфинитив после вводного слова
        "уберите людей?",
    ],
)
def test_not_edit_commands(text: str) -> None:
    assert looks_like_edit(text) is False
